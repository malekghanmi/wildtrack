function generateTrack(baseLat, baseLng, points, speed, wLat, wLng, activities) {
  const track = [];
  let lat = baseLat, lng = baseLng;
  const now = new Date();
  const driftLat = (Math.random() - 0.5) * 0.001;
  const driftLng = (Math.random() - 0.5) * 0.001;
  for (let i = points - 1; i >= 0; i--) {
    const t = new Date(now - i * 3600 * 1000);
    const act = activities[Math.floor(Math.random() * activities.length)];
    const spd =
      act === 'resting'   ? (Math.random() * 0.3) :
      act === 'sleeping'  ? (Math.random() * 0.1) :
      act === 'walking'   ? (Math.random() * speed * 0.4 + 0.8) :
      act === 'foraging'  ? (Math.random() * speed * 0.25 + 0.5) :
      act === 'grazing'   ? (Math.random() * speed * 0.2 + 0.3) :
      act === 'drinking'  ? (Math.random() * 0.2) :
      act === 'hunting' || act === 'running' ? (Math.random() * speed + speed * 0.5) :
      act === 'soaring' || act === 'gliding' ? (Math.random() * speed * 0.8 + speed * 0.3) :
      act === 'swimming'  ? (Math.random() * speed * 0.5 + speed * 0.1) :
      act === 'migrating' ? (Math.random() * speed * 0.9 + speed * 0.4) :
      (Math.random() * speed * 0.3 + 0.4);
    lat += (Math.random() - 0.5) * wLat + driftLat;
    lng += (Math.random() - 0.5) * wLng + driftLng;
    track.push({
      timestamp: t.toISOString(),
      location_lat: +lat.toFixed(5),
      location_long: +lng.toFixed(5),
      ground_speed: +spd.toFixed(2),
      activity: act,
      heading: Math.floor(Math.random() * 360)
    });
  }
  return track;
}

